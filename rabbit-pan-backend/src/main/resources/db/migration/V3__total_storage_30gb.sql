-- ============================================================
-- Rabbit 网盘 · V3：系统总存储空间 50GB -> 30GB
-- 1) total_storage_gb 调整为 30（全用户共享上限）
-- 2) 管理员配额与系统总空间保持一致（仅同步仍为旧默认 50GB 的管理员，避免覆盖手工调整）
-- 说明：V1/V2 已可能被线上库执行过，故不修改其内容，改动统一由本脚本落地。
-- ============================================================

UPDATE `sys_config` SET `config_value` = '30' WHERE `config_key` = 'total_storage_gb';

-- 旧默认 50GB = 53687091200 字节；新默认 30GB = 32212254720 字节
UPDATE `sys_user` SET `storage_total` = 32212254720
WHERE `role` = 'ADMIN' AND `storage_total` = 53687091200;
